/*
 * "WRITTEN IN LIGHT" — studio demo reel. Every pixel and every sound is generated by code in this repo:
 * raymarched GLSL world, liquid chrome, 24k-particle typography, procedural 3D product, SVG morphs, GSAP type,
 * procedural music + SFX, Piper voiceover, Whisper captions. No footage, no stock, no paid AI.
 *
 * Timeline is locked to the music: 120 BPM → 15 frames/beat, 60 frames/bar.
 */
const FPS = 30;
const BAR = 60;
const BEAT = 15;
export const REEL_DURATION = 18 * BAR + 30; // 18 bars + 1s tail

const ss = (f: number, a: number, b: number) => interpolate(f, [a, b], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp", easing: Easing.inOut(Easing.cubic) });

// ---------- shared overlays ----------
const Flash: React.FC<{ at: number; dur?: number; color?: string; peak?: number }> = ({ at, dur = 14, color = "#fff", peak = 0.95 }) => {
  const f = useCurrentFrame();
  const o = interpolate(f, [at - 3, at, at + dur], [0, peak, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  return o > 0 ? <AbsoluteFill style={{ background: color, opacity: o, mixBlendMode: "screen" }} /> : null;
};

const Kicker: React.FC<{ children: React.ReactNode; color?: string }> = ({ children, color = "rgba(244,241,234,0.7)" }) => (
  <div style={{ fontFamily: inter, fontWeight: 600, fontSize: 20, letterSpacing: 7, textTransform: "uppercase", color }}>{children}</div>
);

// ---------- A. surreal cold open + GSAP manifesto ----------
const Manifesto: React.FC = () => {
  const lines = ["No cameras.", "No stock footage.", "No paid AI."];
  const ref = useGsapTimeline((tl, root) => {
    root.querySelectorAll<HTMLElement>(".m-line").forEach((el, i) => {
      const split = SplitText.create(el, { type: "chars" });
      const at = (90 + i * 45) / FPS; // on bar 1.5 / 2.25 / 3 — every 3 beats
      tl.fromTo(split.chars, { yPercent: 110, opacity: 0 }, { yPercent: 0, opacity: 1, stagger: 0.022, duration: 0.5, ease: "expo.out" }, at);
      if (i < lines.length - 1) tl.to(split.chars, { yPercent: -110, opacity: 0, stagger: 0.012, duration: 0.3, ease: "expo.in" }, at + 1.15);
    });
  });
  return (
    <AbsoluteFill ref={ref} style={{ justifyContent: "center", alignItems: "center" }}>
      {lines.map((l) => (
        <div key={l} className="m-line" style={{ position: "absolute", fontFamily: anton, fontSize: 150, color: "#f4f1ea", textTransform: "uppercase", overflow: "hidden", lineHeight: 1.05, letterSpacing: 2, textShadow: "0 10px 60px rgba(0,0,0,0.5)" }}>
          {l}
        </div>
      ))}
    </AbsoluteFill>
  );
};

const SceneSurreal: React.FC<{ dolly: [number, number]; rise?: [number, number]; sun?: number; dur: number }> = ({ dolly, rise = [0, 0], sun = 0.3, dur }) => {
  const f = useCurrentFrame();
  const p = interpolate(f, [0, dur], [0, 1], { extrapolateRight: "clamp", easing: Easing.bezier(0.3, 0, 0.3, 1) });
  return (
    <ShaderCanvas
      fragment={SURREAL_WORLD}
      uniforms={{ ...(SURREAL_DUSK as unknown as Record<string, [number, number, number]>), uDolly: dolly[0] + (dolly[1] - dolly[0]) * p, uRise: rise[0] + (rise[1] - rise[0]) * p, uSun: sun, uOrb: 0.4 + 0.4 * Math.sin(f / 20) }}
    />
  );
};

// ---------- B. liquid gold ----------
const SceneLiquid: React.FC = () => {
  const f = useCurrentFrame();
  const { fps } = useVideoConfig();
  const pulse = beatPulse(f + 240, fps, beatMap.kicks, 9);
  return (
    <AbsoluteFill>
      <LiquidChrome pulse={pulse} amp={0.16 + 0.05 * pulse} tint={[1.25, 0.95, 0.62]} iridescence={0.35} orbit={f * 0.006} dist={7.4} lookY={-0.08} background="#0a0806" bloom={0.4} />
      <AbsoluteFill style={{ justifyContent: "flex-end", alignItems: "center", paddingBottom: 190 }}>
        <Kicker color="#e8c26a">Scene 02 — liquid metal · GLSL</Kicker>
        <div style={{ height: 14 }} />
        <KineticText text="Written in code" fontFamily={instrumentSerif} fontSize={96} style="blur-in" stagger={4} delay={14} color="#f4f1ea" emphasize={["code"]} accent="#e8c26a" />
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// ---------- C. particles → CODE → burst ----------
const SceneParticles: React.FC = () => {
  const f = useCurrentFrame();
  return (
    <AbsoluteFill>
      <ParticleMorph text="CODE" font={anton} form={ss(f, 8, 78)} explode={interpolate(f, [112, 140], [0, 1.2], { extrapolateLeft: "clamp", extrapolateRight: "clamp", easing: Easing.out(Easing.cubic) })} orbit={-0.35 + f * 0.005} colorA="#ff7a45" colorB="#9cc3ff" fade={1 - 0.85 * ss(f, 112, 134)} size={30} />
      <AbsoluteFill style={{ justifyContent: "flex-end", alignItems: "center", paddingBottom: 170, opacity: ss(f, 70, 82) * (1 - ss(f, 108, 114)) }}>
        <Kicker>24,000 particles · curl noise · GPU</Kicker>
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// ---------- D. product film ----------
const Callout: React.FC<{ at: number; x: number; y: number; title: string; sub: string; side?: "left" | "right" }> = ({ at, x, y, title, sub, side = "right" }) => {
  const f = useCurrentFrame();
  const p = ss(f, at, at + 12);
  const out = ss(f, at + 60, at + 70);
  return (
    <div style={{ position: "absolute", left: x, top: y, opacity: p * (1 - out), transform: `translateX(${(1 - p) * (side === "right" ? 30 : -30)}px)`, textAlign: side === "right" ? "left" : "right" }}>
      <div style={{ width: 120 * p, height: 1, background: "#e8c26a", marginBottom: 12, marginLeft: side === "left" ? "auto" : 0 }} />
      <div style={{ fontFamily: instrumentSerif, fontSize: 52, color: "#f4f1ea", lineHeight: 1 }}>{title}</div>
      <div style={{ fontFamily: inter, fontSize: 18, letterSpacing: 4, color: "rgba(244,241,234,0.6)", textTransform: "uppercase", marginTop: 8 }}>{sub}</div>
    </div>
  );
};

const SceneProduct: React.FC = () => {
  const f = useCurrentFrame();
  const fonts = { display: anton, body: inter };
  return (
    <AbsoluteFill>
      {/* shot 1 (bars 9–11): slow push-in, low angle, turntable */}
      <Sequence durationInFrames={120}>
        <ProductStage fonts={fonts} spin={-0.25 + f * 0.004} orbit={0.75 - ss(f, 0, 120) * 0.5} dist={11.5 - ss(f, 0, 120) * 3} height={0.9} lookY={1.3} sweep={-1.5 + f * 0.035} />
        <Callout at={20} x={1330} y={380} title="Glass" sub="transmission · IOR 1.5" />
        <Callout at={50} x={170} y={560} title="Light" sub="three-point + studio env" side="left" />
      </Sequence>
      {/* shot 2 (bar 11): macro on the cap — cut on the downbeat */}
      <Sequence from={120} durationInFrames={60}>
        <ProductStage fonts={fonts} spin={0.4 + (f - 120) * 0.006} orbit={-0.6 + (f - 120) * 0.004} dist={4.4} height={2.9} lookY={2.15} sweep={(f - 120) * 0.06 - 1} sweepIntensity={3} bloom={0.15} />
        <Callout at={8} x={1340} y={430} title="Metal" sub="faceted · clearcoat" />
      </Sequence>
      {/* shot 3 (bar 12): hero wide + brand lockup */}
      <Sequence from={180} durationInFrames={60}>
        <ProductStage fonts={fonts} spin={(f - 180) * 0.01} orbit={0.15} dist={9.5 - ss(f, 180, 240) * 0.8} height={1.4} lookY={1.25} sweep={1.2 - (f - 180) * 0.05} />
        <AbsoluteFill style={{ justifyContent: "center", alignItems: "flex-end", paddingRight: 220 }}>
          <div style={{ textAlign: "right", opacity: ss(f, 184, 196) }}>
            <div style={{ fontFamily: anton, fontSize: 120, color: "#f4f1ea", letterSpacing: 10 }}>NOIR</div>
            <div style={{ fontFamily: instrumentSerif, fontSize: 48, color: "#e8c26a", marginTop: -6 }}>eau de code</div>
          </div>
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

// ---------- E. morph montage, one cut per beat ----------
const WORDS = ["Morph", "Motion", "Depth", "Type", "Rhythm", "Light", "Particles", "Sound"];
const PALETTES: [number, number, number][][] = [
  [[0.04, 0.03, 0.08], [1.0, 0.3, 0.18], [0.18, 0.4, 1.0]],
  [[0.01, 0.03, 0.04], [0.04, 0.5, 0.46], [0.85, 0.5, 0.18]],
];
const SceneMorph: React.FC = () => {
  const f = useCurrentFrame();
  const i = Math.min(WORDS.length - 1, Math.floor(f / BEAT));
  const local = f - i * BEAT;
  const pal = PALETTES[Math.floor(i / 4) % 2];
  const enter = interpolate(f, [0, 10], [1.35, 1], { extrapolateRight: "clamp", easing: Easing.out(Easing.cubic) });
  const blur = interpolate(f, [0, 10], [16, 0], { extrapolateRight: "clamp" });
  return (
    <AbsoluteFill style={{ transform: `scale(${enter})`, filter: blur > 0.1 ? `blur(${blur}px)` : undefined }}>
      <ShaderCanvas fragment={LIQUID_GRADIENT} uniforms={{ uA: pal[0], uB: pal[1], uC: pal[2], uFlow: 3 }} />
      <AbsoluteFill style={{ justifyContent: "center", alignItems: "center" }}>
        <div style={{ transform: `rotate(${f * 0.6}deg)`, opacity: 0.95 }}>
          <MorphShape shapes={["circle", "star", "blob", "hexagon", "burst", "triangle", "diamond", "blob", "circle"]} morphFrames={10} holdFrames={5} fills={["#ff4d2e", "#e8c26a", "#2e6bff"]} size={620} />
        </div>
      </AbsoluteFill>
      <AbsoluteFill style={{ justifyContent: "center", alignItems: "center" }}>
        <div style={{ fontFamily: anton, fontSize: 210, color: "#f4f1ea", textShadow: "0 12px 50px rgba(0,0,0,0.65)", textTransform: "uppercase", letterSpacing: 4, transform: `translateY(${interpolate(local, [0, 6], [40, 0], { extrapolateRight: "clamp", easing: Easing.out(Easing.cubic) })}px) scale(${interpolate(local, [0, 4, 15], [1.08, 1, 0.98])})` }}>
          {WORDS[i]}
        </div>
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// ---------- F. outro ----------
const SceneOutro: React.FC = () => {
  const f = useCurrentFrame();
  const fadeOut = interpolate(f, [165, 210], [1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  return (
    <AbsoluteFill style={{ opacity: fadeOut }}>
      <SceneSurreal dolly={[22, 30]} rise={[0, 3.2]} sun={0.55} dur={210} />
      <AbsoluteFill style={{ background: `rgba(0,0,0,${0.35 * ss(f, 60, 90)})` }} />
      <AbsoluteFill style={{ justifyContent: "center", alignItems: "center", flexDirection: "column" }}>
        <KineticText text="Written in light" fontFamily={anton} fontSize={170} style="track-in" by="char" stagger={1.6} delay={10} uppercase color="#f4f1ea" />
        <div style={{ height: 22 }} />
        <div style={{ opacity: ss(f, 70, 90), display: "flex", flexDirection: "column", alignItems: "center", gap: 14 }}>
          <div style={{ fontFamily: instrumentSerif, fontSize: 54, color: "#e8c26a" }}>AI Creative Studio</div>
          <Kicker>100% open source · zero paid AI · every frame procedural</Kicker>
        </div>
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// ---------- master ----------
export const Reel: React.FC = () => {
  const { durationInFrames } = useVideoConfig();
  const s = (sec: number) => Math.round(sec * FPS);
  return (
    <AbsoluteFill style={{ background: "#000" }}>
      <FilmLook grain={0.14} vignette={0.38} letterbox={2.39} flicker={0.015}>
        <Sequence durationInFrames={4 * BAR}>
          <SceneSurreal dolly={[0, 14]} sun={0.28} dur={4 * BAR} />
          <Manifesto />
        </Sequence>
        <Sequence from={4 * BAR} durationInFrames={3 * BAR}>
          <SceneLiquid />
        </Sequence>
        <Sequence from={7 * BAR} durationInFrames={2 * BAR + 20}>
          <SceneParticles />
        </Sequence>
        <Sequence from={9 * BAR} durationInFrames={4 * BAR}>
          <SceneProduct />
        </Sequence>
        <Sequence from={13 * BAR} durationInFrames={2 * BAR}>
          <SceneMorph />
        </Sequence>
        <Sequence from={15 * BAR} durationInFrames={durationInFrames - 15 * BAR}>
          <SceneOutro />
        </Sequence>
        {/* cuts that land on the music's impacts */}
        <Flash at={4 * BAR} />
        <Flash at={9 * BAR} dur={18} />
        <Flash at={15 * BAR} dur={20} color="#ffd2a8" />
        <Flash at={7 * BAR} dur={6} color="#9cc3ff" peak={0.5} />
        <Flash at={13 * BAR} dur={6} peak={0.6} />
      </FilmLook>
      {/* subtitles live in the lower letterbox bar — cinematic, never over the picture */}
      <Subtitles captions={captions as Caption[]} style={{ fontFamily: inter, fontSize: 30, color: "rgba(244,241,234,0.6)", highlight: "#ffffff", y: 0.937 }} />

      {/* ---- sound ---- */}
      <Audio src={staticFile("reel/music.wav")} volume={(f) => 0.82 * interpolate(f, [durationInFrames - 40, durationInFrames], [1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" })} />
      {vo.map((line) => (
        <Sequence key={line.id} from={s(line.atSec)} durationInFrames={s(line.durationSec) + 10}>
          <Audio src={staticFile(`reel/vo/${line.file}`)} volume={1.0} />
        </Sequence>
      ))}
      <Sequence from={7 * BAR - 4} durationInFrames={20}><Audio src={staticFile("sfx/glitch.wav")} volume={0.45} /></Sequence>
      <Sequence from={7 * BAR + 72} durationInFrames={60}><Audio src={staticFile("sfx/shimmer.wav")} volume={0.6} /></Sequence>
      <Sequence from={9 * BAR + 120 - 5} durationInFrames={25}><Audio src={staticFile("sfx/whoosh.wav")} volume={0.5} /></Sequence>
      <Sequence from={9 * BAR + 180 - 5} durationInFrames={25}><Audio src={staticFile("sfx/whoosh.wav")} volume={0.5} /></Sequence>
      <Sequence from={13 * BAR - 6} durationInFrames={25}><Audio src={staticFile("sfx/whoosh.wav")} volume={0.6} /></Sequence>
      {Array.from({ length: 8 }, (_, i) => (
        <Sequence key={i} from={13 * BAR + i * BEAT} durationInFrames={6}><Audio src={staticFile("sfx/tick.wav")} volume={0.25} /></Sequence>
      ))}
    </AbsoluteFill>
  );
};

