import React from "react";
import { AbsoluteFill, Audio, Sequence, interpolate, staticFile, useVideoConfig, type CalculateMetadataFunction } from "remotion";
import type { Caption } from "@remotion/captions";
import type { CommercialSpec, Timeline } from "./types";
import { getStyle } from "./styles";
import { BLOCKS } from "./blocks";
import { KineticType } from "./Type";
import { SceneShell, OVERLAP, FlashAt, Shockwave, Sparks } from "./transitions";
import { FilmLook } from "../lib/FilmLook";
import { Subtitles } from "../lib/Subtitles";
import { useFormat } from "./format";

export const framesPerBeat = (spec: CommercialSpec) => (spec.fps * 60) / spec.music.bpm;

/** Scene timeline from the beat grid. Incoming scenes start `OVERLAP[transition]` frames early for real overlaps. */
export const buildTimeline = (spec: CommercialSpec): Timeline => {
  const fpb = framesPerBeat(spec);
  let beat = 0;
  const tl = spec.scenes.map((scene, index) => {
    const start = Math.round(beat * fpb);
    beat += scene.beats;
    const end = Math.round(beat * fpb);
    return { scene, index, start, dur: end - start, enterOv: index === 0 ? 0 : OVERLAP[scene.transition ?? "cut"], exitOv: 0 };
  });
  tl.forEach((t, i) => { if (tl[i + 1]) t.exitOv = tl[i + 1].enterOv; });
  return tl;
};

export const commercialDuration = (spec: CommercialSpec) => {
  const tl = buildTimeline(spec);
  const last = tl[tl.length - 1];
  return last.start + last.dur + (spec.tailFrames ?? 0);
};

export type CommercialProps = {
  spec: CommercialSpec;
  /** Loaded in calculateMetadata from remotion/public/commercials/<id>/ (generated by scripts/pipeline/commercial.mjs assets). */
  assets?: { kicks: number[]; vo: { id: string; file: string; atSec: number; durationSec: number }[]; captions: Caption[]; hasMusic: boolean };
};

export const calculateCommercialMetadata: CalculateMetadataFunction<CommercialProps> = async ({ props }) => {
  const base = `commercials/${props.spec.id}`;
  const get = async <T,>(p: string, d: T): Promise<T> => {
    try { const r = await fetch(staticFile(`${base}/${p}`)); return r.ok ? ((await r.json()) as T) : d; } catch { return d; }
  };
  const beats = await get<{ kicks?: number[] } | null>("music.beats.json", null);
  const vo = await get<CommercialProps["assets"] extends infer A ? (A extends { vo: infer V } ? V : never) : never>("vo/vo.json", []);
  const captions = await get<Caption[]>("captions.json", []);
  return {
    durationInFrames: commercialDuration(props.spec),
    fps: props.spec.fps,
    props: { ...props, assets: { kicks: beats?.kicks ?? [], vo, captions, hasMusic: !!beats } },
  };
};

const SfxAt: React.FC<{ name: string; from: number; volume?: number }> = ({ name, from, volume = 0.5 }) => (
  <Sequence from={Math.max(0, from)} durationInFrames={90}><Audio src={staticFile(`sfx/${name}.wav`)} volume={volume} /></Sequence>
);

/** Renders any CommercialSpec: scenes on the beat grid, transitions, kinetic type, VFX, music, SFX, VO and subtitles. */
export const Commercial: React.FC<CommercialProps> = ({ spec, assets }) => {
  const { durationInFrames } = useVideoConfig();
  const f = useFormat();
  const style = getStyle(spec.style);
  const fpb = framesPerBeat(spec);
  const tl = buildTimeline(spec);
  const kicks = assets?.kicks ?? [];
  // the endcard carries its line as typography — drop subtitles that would duplicate it there
  const endcard = tl.find((t) => t.scene.block === "endcard");
  const spb = 60 / spec.music.bpm;
  const muted = (spec.voiceover ?? []).filter((v) => v.subtitle === false).map((v) => {
    const a = assets?.vo.find((x) => x.id === v.id);
    return [v.atBeat * spb * 1000 - 50, (v.atBeat * spb + (a?.durationSec ?? 3)) * 1000 + 50];
  });
  const subs = (assets?.captions ?? []).filter((c) => (!endcard || c.startMs / 1000 < (endcard.start - endcard.enterOv) / spec.fps) && !muted.some(([a, b]) => c.startMs >= a && c.startMs <= b));
  return (
    <AbsoluteFill style={{ background: style.palette.bg }}>
      <FilmLook grain={style.film.grain} vignette={style.film.vignette} tint={style.film.tint} letterbox={f.vertical ? undefined : style.film.letterbox} flicker={0.01}>
        {tl.map((t) => {
          const Block = BLOCKS[t.scene.block];
          const from = t.start - t.enterOv;
          const dur = t.dur + t.enterOv;
          const next = tl[t.index + 1];
          return (
            <Sequence key={t.scene.id} from={from} durationInFrames={dur} name={`${t.scene.id} ${t.scene.block}`}>
              <SceneShell id={t.scene.id} enter={t.scene.transition} enterOv={t.enterOv} exit={next?.scene.transition} exitOv={t.exitOv} accent={style.palette.accent} accent2={style.palette.accent2}>
                <Block ctx={{ spec, scene: t.scene, style, fpb, kicks, sceneStartSec: from / spec.fps }} />
                {(t.scene.text ?? []).map((o, i) => {
                  const a = t.enterOv + Math.round((o.at ?? 0) * fpb);
                  const u = o.until !== undefined ? t.enterOv + Math.round(o.until * fpb) : dur;
                  return (
                    <Sequence key={i} from={a} durationInFrames={Math.max(1, u - a)} layout="none">
                      <KineticType o={o} style={style} durationFrames={Math.max(1, u - a)} />
                    </Sequence>
                  );
                })}
                {(t.scene.vfx ?? []).map((v, i) => {
                  const at = t.enterOv + Math.round(v.atBeat * fpb);
                  const col = v.color ?? style.palette.accent;
                  return v.kind === "shockwave" ? <Shockwave key={i} at={at} color={col} /> : v.kind === "sparks" ? <Sparks key={i} at={at} color={col} /> : <FlashAt key={i} at={at} color={col} />;
                })}
              </SceneShell>
            </Sequence>
          );
        })}
        {/* flash cuts */}
        {tl.filter((t) => t.scene.transition === "flash").map((t) => <FlashAt key={t.scene.id} at={t.start} color={style.palette.paper} />)}
      </FilmLook>
      {subs.length ? (
        <Subtitles captions={subs} style={{ fontFamily: style.fonts.body, fontSize: (f.vertical ? 38 : 30) * f.u, color: "rgba(255,255,255,0.78)", highlight: "#ffffff", y: f.vertical ? 1 - f.safe.bottom / f.height - 0.03 : 0.93, maxWidth: "80%", pill: "rgba(12,10,16,0.42)" }} />
      ) : null}
      {/* ---- sound ---- */}
      {assets?.hasMusic ? <Audio src={staticFile(`commercials/${spec.id}/music.wav`)} volume={(fr) => 0.8 * interpolate(fr, [durationInFrames - 30, durationInFrames], [1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" })} /> : null}
      {(assets?.vo ?? []).map((l) => (
        <Sequence key={l.id} from={Math.round(l.atSec * spec.fps)} durationInFrames={Math.round(l.durationSec * spec.fps) + 10}>
          <Audio src={staticFile(`commercials/${spec.id}/vo/${l.file}`)} volume={1} />
        </Sequence>
      ))}
      {tl.flatMap((t) => (t.scene.sfx ?? []).map((s, i) => <SfxAt key={`${t.scene.id}-${i}`} name={s.name} from={t.start + Math.round(s.atBeat * fpb)} volume={s.volume} />))}
      {/* automatic transition sound design */}
      {tl.slice(1).map((t) => {
        const tr = t.scene.transition ?? "cut";
        if (tr === "whip" || tr === "zoom" || tr === "portal" || tr === "iris") return <SfxAt key={`tr-${t.scene.id}`} name="whoosh" from={t.start - t.enterOv - 4} volume={0.45} />;
        if (tr === "glitch") return <SfxAt key={`tr-${t.scene.id}`} name="glitch" from={t.start - t.enterOv} volume={0.4} />;
        return null;
      })}
    </AbsoluteFill>
  );
};
